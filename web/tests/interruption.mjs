// Pointer interruption must cancel rather than commit engine gestures.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium, webkit } from 'playwright'
import { createServer } from 'vite'

const which = process.argv[2] ?? 'chromium'
const server = await createServer({ configFile: new URL('../vite.config.ts', import.meta.url).pathname, server: { port: 0, host: '127.0.0.1' }, logLevel: 'error' })
await server.listen()
const browser = await (which === 'webkit' ? webkit : chromium).launch()
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const kit = page.frameLocator('#kit')
const input = kit.getByTestId('cad-command-line')
const origin = `http://127.0.0.1:${server.httpServer.address().port}`
const output = new URL('../../temp/interruption/', import.meta.url)
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const inspect = () => page.evaluate(async () => window.devHost.connection().ai.inspect())
const details = async () => (await inspect()).details
const circle = async () => (await details()).selectedObjects.find((object) => object.radius !== undefined)
const until = async (name, check) => {
  for (let attempt = 0; attempt < 100; attempt += 1) {
    if (await check()) { console.log(`PASS ${name}`); return }
    await page.waitForTimeout(100)
  }
  assert.fail(name)
}
const command = async (text) => { await input.fill(text); await input.press('Enter') }
const open = async () => {
  await page.goto(`${origin}/dev.html?modes=classic&locale=en-US`)
  await page.waitForFunction(() => window.devHost?.connection(), null, { timeout: 60_000 })
  await until('sample ready', async () => (await details()).entities === 7)
}
const grip = async () => {
  await page.mouse.click(737, 528)
  await until('circle selected', async () => (await circle())?.radius === 30)
  await page.mouse.click(737, 592)
  await until('grip active', async () => (await details()).prompt.startsWith('STRETCH '))
}
const screenshot = async (name) => page.screenshot({ path: new URL(`${which}-${name}.png`, output).pathname })
const surface = kit.getByTestId('kit-canvas-surface')
const watchPointer = async () => surface.evaluate((canvas) => {
  canvas.dataset.lostCapture = '0'
  canvas.dataset.gotCapture = '0'
  canvas.addEventListener('pointerdown', (event) => { canvas.dataset.pointerId = String(event.pointerId) }, { once: true })
  canvas.addEventListener('lostpointercapture', (event) => {
    canvas.dataset.lostCapture = String(Number(canvas.dataset.lostCapture) + 1)
    canvas.dataset.trustedLoss = String(event.isTrusted)
  })
  canvas.addEventListener('gotpointercapture', () => { canvas.dataset.gotCapture = String(Number(canvas.dataset.gotCapture) + 1) })
})
const interrupt = async (kind) => {
  if (kind === 'cancel') {
    await surface.evaluate((canvas) => canvas.dispatchEvent(new PointerEvent('pointercancel', { bubbles: true, pointerId: Number(canvas.dataset.pointerId), pointerType: 'mouse' })))
  } else {
    // setPointerCapture is pending until the next pointer event. Acquire it before releasing it.
    await page.mouse.move(819, 560)
    await until('the browser acquires pointer capture', async () => Number(await surface.getAttribute('data-got-capture')) > 0)
    await surface.evaluate((canvas) => canvas.releasePointerCapture(Number(canvas.dataset.pointerId)))
    // Capture transitions are processed before the next pointer event.
    await page.mouse.move(821, 560)
    await until('the browser reports lost pointer capture', async () => Number(await surface.getAttribute('data-lost-capture')) > 0)
    assert.equal(await surface.getAttribute('data-trusted-loss'), 'true', 'capture loss is generated by the browser')
  }
}

try {
  await mkdir(output, { recursive: true })
  for (const kind of process.argv[3] ? [process.argv[3]] : ['cancel', 'lost-capture']) {
    await open()
    await grip()
    await watchPointer()
    await page.mouse.move(820, 560)
    await page.mouse.down()
    await interrupt(kind)
    await page.mouse.up()
    await until(`${kind}: interrupted grip leaves the drawing clean`, async () => !(await inspect()).dirty && !(await details()).prompt.startsWith('STRETCH '))
    assert.deepEqual((await circle())?.center, [235, 130])
    assert.equal((await details()).selection, 1)
    await screenshot(`${kind}-grip`)
    await page.mouse.click(737, 592)
    await until(`${kind}: a new grip starts immediately`, async () => (await details()).prompt.startsWith('STRETCH '))
    await page.mouse.click(820, 560)
    await until(`${kind}: a normal release commits and retains selection`, async () => (await inspect()).dirty && (await details()).selection === 1 && (await circle())?.center[0] > 260)
    const center = (await circle()).center
    await kit.getByTestId('cad-undo').click()
    await until(`${kind}: one Undo restores the clean drawing`, async () => !(await inspect()).dirty)
    await kit.getByTestId('cad-redo').click()
    await kit.getByTestId('cad-save').click()
    await until(`${kind}: the subsequent edit saves cleanly`, async () => !(await inspect()).dirty)
    await page.evaluate(async () => { const file = window.devHost.files.get('Sample.dxf'); await window.devHost.open('Sample.dxf', file.bytes) })
    await command('selectall')
    await until(`${kind}: saved coordinates survive reopening`, async () => JSON.stringify((await circle())?.center) === JSON.stringify(center))

    await open()
    await command('line')
    await until(`${kind}: LINE requests its first point`, async () => (await details()).prompt.includes('first point'))
    await command('20,20')
    await until(`${kind}: LINE requests its next point`, async () => (await details()).prompt.includes('next point'))
    await watchPointer()
    await page.mouse.move(820, 560)
    await page.mouse.down()
    await interrupt(kind)
    await page.mouse.up()
    await until(`${kind}: an interrupted LINE adds no segment`, async () => !(await details()).running && (await details()).entities === 7 && !(await inspect()).dirty)

    await open()
    await watchPointer()
    await page.mouse.move(650, 480)
    await page.mouse.down()
    await page.mouse.move(820, 700, { steps: 4 })
    await interrupt(kind)
    await page.mouse.up()
    await until(`${kind}: interrupted selection drag stays empty and clean`, async () => (await details()).selection === 0 && !(await inspect()).dirty)
    await page.mouse.click(737, 528)
    await until(`${kind}: the next click selects the circle normally`, async () => (await circle())?.radius === 30)
    await page.mouse.click(737, 592)
    await until(`${kind}: no stale selection window blocks the next grip`, async () => (await details()).prompt.startsWith('STRETCH '))
    await input.press('Escape')
    await until(`${kind}: the next grip cancels cleanly`, async () => !(await details()).prompt.startsWith('STRETCH ') && (await details()).selection === 1 && !(await inspect()).dirty)
  }
  assert.deepEqual(errors, [])
} catch (error) {
  await screenshot('failure').catch(() => {})
  throw error
} finally {
  await browser.close()
  await server.close()
}
