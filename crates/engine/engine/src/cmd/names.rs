/// The name typed at the command line for command `id`, when it is not the id itself.
pub fn typed(id: &str) -> Option<&'static str> {
    TYPED.binary_search_by(|(known, _)| (*known).cmp(id)).ok().and_then(|at| TYPED.get(at)).map(|(_, name)| *name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_names_only_commands() {
        assert!(TYPED.windows(2).all(|pair| pair[0].0 < pair[1].0), "sorted by id, no id twice");
        let mut names: Vec<&str> = TYPED.iter().map(|(_, name)| *name).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), TYPED.len(), "no typed name twice");
        for (id, name) in TYPED {
            assert!(crate::cmd::find_command(id).is_some(), "{id} is not a command");
            assert_eq!(*name, name.to_ascii_lowercase(), "typed names are lower case");
        }
    }
}
